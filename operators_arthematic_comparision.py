print(f"{a} / {b} = {a / b:.2f}")   # Float division
print(f"{a} // {b} = {a // b}")     # Floor division
print(f"{a} % {b} = {a % b}")       # Modulus

print("Comparison Operators")
print(f"{a} == {b} : {a == b}")
print(f"{a} != {b} : {a != b}")
print(f"{a} > {b}  : {a > b}")
print(f"{a} < {b}  : {a < b}")
print(f"{a} >= {b} : {a >= b}")
print(f"{a} <= {b} : {a <= b}")

print("Logical Operators")
print(f"{a} > 5 and {b} < 5 : {a > 5 and b < 5}")
